#include <stdio.h>

/* NOTE: In C, the entry point is the function "main" whose arguments are the
 *       command line arguments; if they aren't needed, we can instead declare
 *       them as "void" to reassure the compiler that we didn't just forget
 *       about them. */
int main(void) {
    printf("Hello, world!\n");

    return 0;
}
